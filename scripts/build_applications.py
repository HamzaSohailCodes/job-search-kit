#!/usr/bin/env python3
"""Build applications/<company>.md from the tracker export and the saved form snapshots.

Inputs
  tracker/tracker.csv            full export of the tracker tab (tracker.gid, default 0), columns A..AC
                                 (see scripts/tracker_header.md). A..Q are read by position, R..AC by
                                 header name, so exports that stop at Q or R still work. Full-time and
                                 contract rows share the tab; column L tells them apart.
  applications/_forms/*.json     one snapshot per filled form (written by apply-batch)
  applications/_events.jsonl     event history (scripts/log_event.py), rendered as a Timeline per role

Each company file has an auto-generated block between AUTO markers; anything you write
outside the markers (e.g. a "## My notes" section) is kept when the script reruns.

Data location: the repo root, or $JOB_KIT_DATA if set (tests point it at a temp copy of fixtures).
Skipped (exit 0) when modules.record_keeping is false in config/profile.json.

A company file is written for rows in --statuses, for any company with a form snapshot, and for contract rows
whose Contacted On (AA) is set.

Usage: python3 scripts/build_applications.py [--csv tracker/tracker.csv] [--statuses Applied,Rejected,Interviewing,Offer]
"""
import argparse, csv, datetime as _dt, glob, json, os, re, sys

_d = os.path.dirname(os.path.abspath(__file__))
while not os.path.exists(os.path.join(_d, "core", "config.py")) and _d != os.path.dirname(_d):
    _d = os.path.dirname(_d)
sys.path.insert(0, _d)
from core import config  # noqa: E402

START, END = '<!-- AUTO:START (generated by scripts/build_applications.py; edit outside these markers) -->', '<!-- AUTO:END -->'
REPLY_EVENTS = ('interview', 'assessment', 'offer', 'rejected', 'withdrawn', 'no_response')


def data_root():
    """Where applications/, tracker/, resumes/, reviews/ ... live. $JOB_KIT_DATA overrides the repo root."""
    return os.path.abspath(os.path.expanduser(os.environ.get('JOB_KIT_DATA') or config.ROOT))


def dpath(*parts):
    return os.path.join(data_root(), *parts)


# kept for callers that import ROOT; resolved at import time, prefer data_root() in new code
ROOT = data_root()

_PROFILE = {}


def read_text(path):
    with open(path, encoding='utf-8') as f:
        return f.read()


def write_text(path, text):
    with open(path, 'w', encoding='utf-8') as f:
        f.write(text)


def read_json(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def read_csv(path, dict_rows=False):
    with open(path, encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f) if dict_rows else csv.reader(f))


def profile():
    """The candidate profile (cached per profile path). Missing profile -> defaults only."""
    key = config.profile_path()
    if key not in _PROFILE:
        _PROFILE[key] = config.load(required=False) or config._example_defaults()
    return _PROFILE[key]


def record_keeping_on(p=None):
    return bool(config.get(p if p is not None else profile(), 'modules.record_keeping', True))


def slug(name):
    s = re.sub(r'\b(inc|llc|ltd|corp|co)\b\.?', '', name.lower())
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-') or 'unknown'


def company_key(name):
    return slug(name).replace('-', '')


def resume_of(notes, applied_date=None, p=None):
    """Resume sent, from a 'resume: <label>' note in tracker column I, matched to config resumes[].label."""
    labels = config.resume_labels(p if p is not None else profile())
    m = re.search(r'resume:\s*([A-Za-z0-9_.()/-]+)', notes or '', re.I)
    if m:
        got = m.group(1).strip().rstrip('.,;')
        for label, desc in labels.items():
            if label and label.lower() == got.lower():
                return desc
        if got.lower().startswith('tailored'):
            return 'tailored resume (see resumes/tailored/ and the form snapshot below)'
        return f'{got} (label not in config resumes[])'
    return 'not recorded in the tracker (see resumes/archive/ for the versions in use on that date)'


def load_events(path=None):
    ev = {}
    p = path or dpath('applications', '_events.jsonl')
    if os.path.exists(p):
        for line in read_text(p).splitlines():
            try:
                o = json.loads(line)
            except Exception:
                continue
            ev.setdefault(company_key(o.get('company', '')), []).append(o)
    return ev


def role_events(events, title):
    t = (title or '').lower()
    mine = [e for e in events if not e.get('role') or e['role'].lower()[:25] in t or t[:25] in e['role'].lower()]
    mine = sorted(mine, key=lambda e: e.get('date', ''))
    # merge same-day 'filled' events into one line
    out = []
    for e in mine:
        if e.get('event') == 'filled' and out and out[-1].get('event') == 'filled' and out[-1].get('date') == e.get('date'):
            out[-1] = dict(out[-1], detail=(out[-1].get('detail', '') + ' / ' + e.get('detail', '')).strip(' /'))
        else:
            out.append(dict(e))
    return out


# Columns after Q, read by header name (position is the fallback when no header row is passed)
EXTRA_COLS = {'Reached Interview': 17, 'Rate / Terms': 18, 'Priority': 19, 'Recruiter Email': 20,
              'Recruiter Name / LinkedIn': 21, 'Resume to Send': 22, 'Contacted On': 26,
              'Follow-up 1': 27, 'Follow-up 2': 28}
CONTRACT_STAGES = ('Not contacted', 'Emailed', 'Connected', 'Replied', 'Screen call', 'Submitted (RTR)', 'Client interview')
REPLIED_STAGES = ('Replied', 'Screen call', 'Submitted (RTR)', 'Client interview')


def extras(r, header=None):
    """{header: value} for the R..AC columns of one row; '' for columns the export doesn't have."""
    out = {}
    idx = {h.strip(): i for i, h in enumerate(header)} if header else None
    for name, pos in EXTRA_COLS.items():
        i = idx.get(name) if idx is not None else pos
        out[name] = r[i].strip() if i is not None and i < len(r) else ''
    return out


def is_contract(etype_label):
    t = config.employment_type_of(etype_label)
    return t in getattr(config, 'CONTRACT_TYPES', ()) or t == 'contract'


def employment_segment(etype_label):
    """Normalised column-L label for reports: 'contract (c2c)' -> 'Contract (C2C)', blank -> 'Not stated'."""
    t = config.employment_type_of(etype_label)
    if t in getattr(config, 'EMPLOYMENT_TYPES', {}):
        return config.employment_label(t)
    if t == 'contract':
        return 'Contract'
    return (etype_label or '').strip() or 'Not stated'


def outreach_stage(outcome):
    """The contract outreach stage word at the start of column O, or ''."""
    o = (outcome or '').strip().lower()
    return next((s for s in CONTRACT_STAGES if o.startswith(s.lower())), '')


def add_workdays(d, n):
    """Sheets WORKDAY(d, n) without holidays: n Monday-to-Friday days after d."""
    while n > 0:
        d += _dt.timedelta(days=1)
        if d.weekday() < 5:
            n -= 1
    return d


def contract_followup_dates(contacted, fu1='', fu2='', p=None, parse=None):
    """(follow-up 1, follow-up 2) dates for a contract row: columns AB/AC when the export has them,
    else Contacted On (AA) + c2c.followup_workdays (default [3, 5])."""
    parse = parse or _iso
    c = parse(contacted)
    if not c:
        return None, None
    n = list(config.get(p if p is not None else profile(), 'c2c.followup_workdays', None) or [3, 5]) + [3, 5]
    return (parse(fu1) or add_workdays(c, int(n[0])), parse(fu2) or add_workdays(c, int(n[1])))


def _iso(s):
    s = (s or '').strip().lstrip('~')
    for fmt in ('%Y-%m-%d', '%m/%d/%Y', '%m/%d/%y', '%Y/%m/%d'):
        try:
            return _dt.datetime.strptime(s[:10] if fmt == '%Y-%m-%d' else s, fmt).date()
        except ValueError:
            continue
    return None


def follow_up_days(p=None):
    return int(config.get(p if p is not None else profile(), 'followups.quiet_days', 10) or 10)


def waiting_line(status, applied, evs, today=None, p=None):
    """'No reply for N days' signal for Applied rows with no later outcome event."""
    if status != 'Applied' or not applied:
        return ''
    try:
        d0 = _dt.date.fromisoformat(applied[:10])
    except ValueError:
        return ''
    if any(e.get('event') in REPLY_EVENTS for e in evs):
        return ''
    days_due = follow_up_days(p)
    days = ((today or _dt.date.today()) - d0).days
    due = d0 + _dt.timedelta(days=days_due)
    flag = ' **(stale)**' if days > days_due else ''
    return f"Waiting: no reply for {days} day(s) since {d0}; follow up on {due}{flag}"


def render_timeline(evs):
    if not evs:
        return ['### Timeline', '', '_No events logged yet._', '']
    out = ['### Timeline', '', '| Date | Event | Detail | Source |', '|---|---|---|---|']
    for e in evs:
        d = e.get('detail', '').replace('|', '/').replace('\n', ' ')
        if e.get('reason'):
            d = f"[{e['reason']}] " + d
        out.append(f"| {e.get('date','')} | **{e.get('event','')}** | {d} | {e.get('source','')} |")
    return out + ['']


def load_forms():
    forms = {}
    root = data_root()
    for p in sorted(glob.glob(os.path.join(root, 'applications', '_forms', '*.json'))):
        try:
            d = read_json(p)
        except Exception:
            continue
        forms.setdefault(company_key(d.get('company', '')), []).append((os.path.relpath(p, root), d))
    return forms


def render_form(path, d):
    root = data_root()
    out = [f"#### Form snapshot ({d.get('captured_at', '?')}, {d.get('source', 'apply-batch')})", '']
    if d.get('form_url'):
        out.append(f"Form: {d['form_url']}")
    if d.get('resume_uploaded'):
        out.append(f"Resume uploaded: {d['resume_uploaded']}")
    if d.get('resume_sha256'):
        out.append(f"Resume pinned: sha256 {d['resume_sha256'][:12]}… → `{d.get('resume_archive', 'resumes/archive/')}`")
    if d.get('salary'):
        out.append(f"Salary entered: {d['salary']}")
    out.append(f"Raw: `{path}`")
    shots = [path.replace('.json', '_confirmation' + ext) for ext in ('.png', '.jpg')]
    shot = next((s for s in shots if os.path.exists(os.path.join(root, s))), None)
    if shot:
        out.append(f"Submission proof: ![confirmation]({os.path.relpath(os.path.join(root, shot), os.path.join(root, 'applications'))})")
    out.append('')
    for qa in d.get('answers', []):
        q = qa.get('question', '').strip().replace('\n', ' ')
        a = str(qa.get('answer', '')).strip()
        note = f" _({qa['note']})_" if qa.get('note') else ''
        out.append(f"- **{q}**{note}")
        for line in (a.splitlines() or ['(blank)']):
            out.append(f"  > {line}" if line.strip() else '  >')
    if d.get('left_for_candidate'):
        who = config.first_name(profile()) if config.get(profile(), 'identity.full_name') else 'the candidate'
        out += ['', f'Left for {who}: ' + '; '.join(d['left_for_candidate'])]
    if d.get('caveat'):
        out += ['', f"_{d['caveat']}_"]
    return out + ['']


def tracker_link(row_no, p=None):
    p = p if p is not None else profile()
    tab = config.get(p, 'tracker.tab', 'Sheet1') or 'Sheet1'
    url = config.sheet_url(p, row_no)
    return f"[{tab} row {row_no}]({url})" if url else f"{tab} row {row_no}"


def contract_waiting_line(x, evs, p=None):
    """Outreach signal for a contract row: contacted date and the two follow-up dates."""
    if not x.get('Contacted On') or any(e.get('event') in REPLY_EVENTS for e in evs):
        return ''
    f1, f2 = contract_followup_dates(x['Contacted On'], x.get('Follow-up 1'), x.get('Follow-up 2'), p)
    if not f1:
        return ''
    return f"Contacted {x['Contacted On']}; follow-up 1 on {f1}, follow-up 2 on {f2}"


def render_role(row_no, r, forms, events=(), p=None, header=None):
    p = p if p is not None else profile()
    title, company, loc, link, pay, status, applied, posted, notes, score, source, etype, issues, jd = (r + [''] * 17)[:14]
    outcome, reason, h1b = (r + [''] * 17)[14:17]
    x = extras(r, header)
    evs = role_events(events, title)
    contract = is_contract(etype)
    wait = (contract_waiting_line(x, evs, p) if contract else '') or waiting_line(status.strip(), applied.strip(), evs, p=p)
    out = [f"## {title}", '',
           '| Field | Value |', '|---|---|',
           f"| Status | **{status or '?'}** |",
           f"| Employment type | {etype or '—'} |",
           f"| Outcome / next step | {outcome or wait or '—'} |",
           f"| Reason tag | {reason or '—'} |"]
    if config.module_on(p, 'h1b') or h1b.strip():
        out.append(f"| H-1B evidence | {h1b or '—'} |")
    out += [f"| Applied date | {applied or 'not recorded'} |",
            f"| Resume sent | {resume_of(notes, applied, p)} |",
            f"| Location | {loc or '—'} |",
            f"| Pay posted | {pay or '—'} |",
            f"| Posted | {posted or '—'} |"]
    if x['Rate / Terms']:
        out.append(f"| Rate / terms | {x['Rate / Terms']} |")
    recruiter = ' · '.join(v for v in (x['Recruiter Name / LinkedIn'], x['Recruiter Email']) if v)
    if recruiter:
        out.append(f"| Recruiter | {recruiter} |")
    if x['Contacted On']:
        out.append(f"| Contacted on | {x['Contacted On']} |")
    if x['Reached Interview']:
        out.append(f"| Reached interview | {x['Reached Interview']} |")
    out += [f"| Match score | {score or '—'} |",
            f"| Source | {source or '—'} |",
            f"| Job link | {link or '—'} |",
            f"| Tracker | {tracker_link(row_no, p)} |", '']
    if notes:
        out += ['**Fit notes (at shortlist time):** ' + notes.replace('\n', ' '), '']
    if issues:
        out += ['**Application issues:** ' + issues.replace('\n', ' '), '']
    out += render_timeline(evs)
    out += ['### What we submitted', '']
    if forms:
        for fp, d in forms:
            out += render_form(fp, d)
    else:
        out += ['_No form snapshot saved for this application._', '']
    out += ['### Job description', '']
    out += [('> ' + l) if l.strip() else '>' for l in (jd or '(not saved)').splitlines()]
    return out + ['']


def write_company(name, roles, forms, events=(), p=None, header=None):
    p = p if p is not None else profile()
    path = dpath('applications', slug(name) + '.md')
    url = config.sheet_url(p)
    used = set()
    head = f"Tracker: [{url}]({url}) · {len(roles)} role(s)" if url else f"Tracker: {config.get(p, 'tracker.tab', 'Sheet1')} · {len(roles)} role(s)"
    body = [START, '', f"# {name}", '', head, '']
    for row_no, r in roles:
        title = r[0].lower()
        mine = [f for f in forms if not f[1].get('job_title') or f[1]['job_title'].lower()[:25] in title or title[:25] in f[1]['job_title'].lower()]
        if len(roles) == 1:
            mine = forms
        used.update(id(f) for f in mine)
        body += render_role(row_no, r, mine, events, p, header)
    left = [f for f in forms if id(f) not in used]
    if left:
        body += ['## Form snapshots not matched to a role', '']
        for fp, d in left:
            body += render_form(fp, d)
    body.append(END)
    auto = '\n'.join(body)
    if os.path.exists(path):
        old = read_text(path)
        if START in old and END in old:
            pre, rest = old.split(START, 1)
            post = rest.split(END, 1)[1]
            text = pre + auto + post
        else:
            text = auto + '\n\n' + old
    else:
        text = auto + '\n\n## My notes\n\n'
    write_text(path, text)
    return path


def main(argv=None):
    ap = argparse.ArgumentParser(description='Regenerate applications/<company>.md from the tracker export and form snapshots.')
    ap.add_argument('--csv', default=None, help='tracker export (default tracker/tracker.csv in the data root)')
    ap.add_argument('--statuses', default='Applied,Rejected,Interviewing,Offer')
    a = ap.parse_args(argv)
    p = profile()
    if not record_keeping_on(p):
        print('modules.record_keeping is off in config/profile.json; skipped')
        return 0
    keep = {s.strip().lower() for s in a.statuses.split(',')}
    csv_path = a.csv or dpath('tracker', 'tracker.csv')
    if not os.path.exists(csv_path):
        print(f'no tracker export at {csv_path}; export the tracker tab to CSV first', file=sys.stderr)
        return 2
    rows = read_csv(csv_path)
    forms = load_forms()
    events = load_events()
    by, names = {}, {}
    for i, r in enumerate(rows[1:], start=2):
        contacted = extras(r, rows[0])['Contacted On']  # contract outreach sent counts as applied
        if len(r) < 6 or not (r[5].strip().lower() in keep or company_key(r[1]) in forms or contacted):
            continue
        k = company_key(r[1])
        names.setdefault(k, r[1].strip())
        by.setdefault(k, []).append((i, r))
    os.makedirs(dpath('applications'), exist_ok=True)
    for k, roles in sorted(by.items()):
        write_company(names[k], roles, forms.get(k, []), events.get(k, []), p, rows[0] if rows else None)
    for k, fs in forms.items():
        if k not in by:
            write_company(fs[0][1].get('company', k), [], fs, events.get(k, []), p)
    print(f"{len(by)} company files, {sum(len(v) for v in by.values())} roles, "
          f"{sum(1 for k in by if k in forms)} with form snapshots")
    return 0


if __name__ == '__main__':
    sys.exit(main())
